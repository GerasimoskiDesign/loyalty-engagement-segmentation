"""PDF report (``python -m loyaltyseg report``): matplotlib figures + ReportLab layout.

Six pages: summary, content clusters, archetypes, segments & opportunity, audiences,
experiment readout. Neutral styling, no branding; every page footer says the data is
synthetic so a printed page cannot be mistaken for real results.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Image,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from loyaltyseg.config import Settings
from loyaltyseg.io import read_json

log = logging.getLogger(__name__)
PAGE_W = A4[0] - 3.6 * cm
FOOTER = "Synthetic data generated by this repository - not real customer results."


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle(
            "h1",
            parent=base["Heading1"],
            fontSize=16,
            spaceAfter=8,
            textColor=colors.HexColor("#0b0b0b"),
        ),
        "h2": ParagraphStyle(
            "h2",
            parent=base["Heading2"],
            fontSize=12,
            spaceAfter=6,
            textColor=colors.HexColor("#0b0b0b"),
        ),
        "body": ParagraphStyle(
            "body",
            parent=base["BodyText"],
            fontSize=9,
            leading=12.5,
            textColor=colors.HexColor("#30302e"),
        ),
        "small": ParagraphStyle(
            "small",
            parent=base["BodyText"],
            fontSize=7.5,
            leading=10,
            textColor=colors.HexColor("#52514e"),
        ),
    }


def _table(
    df: pd.DataFrame, col_widths: list[float] | None = None, font_size: float = 7.5
) -> Table:
    data = [list(df.columns)] + df.astype(str).values.tolist()
    t = Table(data, colWidths=col_widths, repeatRows=1, hAlign="LEFT")
    t.setStyle(
        TableStyle(
            [
                ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", font_size),
                ("FONT", (0, 1), (-1, -1), "Helvetica", font_size),
                ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#30302e")),
                ("LINEBELOW", (0, 0), (-1, 0), 0.6, colors.HexColor("#8a8985")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f4f2")]),
                ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
            ]
        )
    )
    return t


def _img(path: Path, width: float = PAGE_W) -> Image:
    img = Image(str(path))
    ratio = img.imageHeight / img.imageWidth
    img.drawWidth, img.drawHeight = width, width * ratio
    return img


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _footer(canvas: Any, doc: Any) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(colors.HexColor("#8a8985"))
    canvas.drawString(1.8 * cm, 1.0 * cm, FOOTER)
    canvas.drawRightString(A4[0] - 1.8 * cm, 1.0 * cm, f"page {doc.page}")
    canvas.restoreState()


def build_report(s: Settings) -> Path:
    """Assemble the PDF from the outputs of the earlier steps."""
    o = s.output_dir
    st = _styles()
    fig = o / "figures"
    meta = read_json(s.raw_dir / "meta.json")
    ev = read_json(o / "archetypes" / "evaluation.json")
    browsers = read_json(o / "segments" / "browsers.json")
    manifest = read_json(o / "audiences" / f"as_of_{s.as_of.isoformat()}" / "manifest.json")
    ro = read_json(o / "experiment" / "readout.json")
    content_k = read_json(o / "content" / "k.json")
    summary = pd.read_csv(o / "content" / "cluster_summary.csv")
    profile = pd.read_csv(o / "archetypes" / "profile.csv")
    sizes = pd.read_csv(o / "segments" / "layer_sizes.csv")

    out = o / "report" / "loyalty_segmentation_report.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(
        str(out),
        pagesize=A4,
        leftMargin=1.8 * cm,
        rightMargin=1.8 * cm,
        topMargin=1.6 * cm,
        bottomMargin=1.8 * cm,
        title="Loyalty engagement segmentation",
        author="loyaltyseg",
        invariant=1,
    )
    E: list[Any] = []

    # 1. Summary ------------------------------------------------------------------------
    E += [
        Paragraph("Loyalty engagement segmentation", st["h1"]),
        Paragraph(
            f"As of {meta['as_of']} &middot; {meta['users']:,} synthetic users &middot; "
            f"{meta['events']:,} events &middot; seed {meta['seed']}",
            st["small"],
        ),
        Spacer(1, 10),
    ]
    acq, ret = ro["acquisition"], ro["retention"]
    bullets = [
        f"<b>{browsers['browsers']:,} Browsers ({_pct(browsers['browser_share_of_base'])} of "
        f"users)</b> open the app but have never touched the loyalty hub; "
        f"{browsers['reachable_browsers']:,} of them are push-reachable.",
        f"Push reachability: {browsers['reachable_users']:,} users "
        f"({_pct(browsers['reachable_users'] / browsers['base_users'])}).",
        f"Content: {content_k['best_k']} content clusters chosen by silhouette "
        f"(elbow at k={content_k['elbow_k']}).",
        f"Archetypes: Browsers by rule + {ev['best_k_engaged']} clusters of engaged users; "
        f"ARI vs planted archetypes = {ev.get('ari_vs_planted', float('nan')):.3f} "
        "(synthetic data only - real data has no ground truth).",
        f"Simulated campaign: acquisition {_pct(acq['p_a'])} broad vs {_pct(acq['p_b'])} "
        f"targeted (p={acq['p_value']:.2g}); 30-day repeat {_pct(ret['p_a'])} vs "
        f"{_pct(ret['p_b'])} (p={ret['p_value']:.2g}).",
    ]
    for b in bullets:
        E.append(Paragraph(f"&bull; {b}", st["body"]))
    E += [
        Spacer(1, 8),
        Paragraph(
            "Method: catalog items are clustered into content clusters; each user's "
            "depth-weighted interactions with those clusters plus recency, frequency, value, "
            "discount preference and push response form the user feature table; engaged users "
            "are clustered into archetypes; five transparent rule-based layers (lifecycle, "
            "interest, play style, deal style, channel) are added on top and drive campaign "
            "audiences.",
            st["body"],
        ),
        Spacer(1, 8),
        _img(fig / "lifecycle_opportunity.png", PAGE_W * 0.9),
        PageBreak(),
    ]

    # 2. Content clusters -----------------------------------------------------------------
    E += [
        Paragraph("Content clusters", st["h2"]),
        _img(fig / "content_k_selection.png"),
        Spacer(1, 6),
        _table(
            summary.drop(columns=["content_cluster"]).rename(
                columns={
                    "content_cluster_name": "cluster",
                    "dominant_type": "type",
                    "dominant_category": "category",
                    "median_reward_value": "median value",
                    "mean_discount_depth": "discount",
                    "mean_effort": "effort",
                }
            )
        ),
        Spacer(1, 6),
        Paragraph(
            "Names are generated by a deterministic rule from each centroid's "
            "dominant item type, category, frequency, value tier and discount depth.",
            st["small"],
        ),
        PageBreak(),
    ]

    # 3. Archetypes -----------------------------------------------------------------------
    E += [Paragraph("User archetypes", st["h2"])]
    if (fig / "archetype_k_selection.png").exists():
        E.append(_img(fig / "archetype_k_selection.png"))
    prof = profile[
        [
            "archetype",
            "users",
            "share",
            "loyalty_days_per_30d",
            "recency_days_filled",
            "type_share_game",
            "cat_share_tech",
            "cat_share_shopping",
            "discount_pref",
            "push_open_rate_filled",
        ]
    ].copy()
    prof["share"] = prof["share"].map(_pct)
    prof = prof.round(2).rename(
        columns={
            "loyalty_days_per_30d": "active days/30d",
            "recency_days_filled": "recency (d)",
            "type_share_game": "game share",
            "cat_share_tech": "tech share",
            "cat_share_shopping": "shop share",
            "discount_pref": "discount pref",
            "push_open_rate_filled": "push open",
        }
    )
    E += [
        Spacer(1, 4),
        _img(fig / "archetype_profile.png", PAGE_W * 0.95),
        Spacer(1, 4),
        _table(prof, font_size=7),
        Spacer(1, 4),
        Paragraph(
            "k is chosen among stable solutions (mean pairwise ARI across 5 seeds "
            "above the configured threshold) by the best average rank of silhouette "
            "and Davies-Bouldin. Medians for counts, means for shares.",
            st["small"],
        ),
        PageBreak(),
    ]

    # 4. Segments & opportunity -----------------------------------------------------------
    t = sizes.copy()
    for c in ("share_of_base", "reachable_rate", "share_of_reachable"):
        t[c] = t[c].map(_pct)
    t = t.rename(
        columns={
            "reachable_users": "reachable",
            "share_of_base": "% base",
            "reachable_rate": "% reachable",
            "share_of_reachable": "% of reach",
        }
    )
    E += [
        Paragraph("Five-layer segmentation and opportunity sizing", st["h2"]),
        _table(t[t["layer"] != "archetype"], font_size=7),
        Spacer(1, 6),
        Paragraph(
            "Every user has exactly one label per layer. Thresholds: config/segments.yaml.",
            st["small"],
        ),
        PageBreak(),
    ]

    # 5. Audiences -----------------------------------------------------------------------
    rows = [{"audience": a["audience"], **a["counts"]} for a in manifest["audiences"]]
    E += [
        Paragraph("Campaign audiences", st["h2"]),
        _img(fig / "audiences.png", PAGE_W * 0.9),
        Spacer(1, 6),
        _table(pd.DataFrame(rows), font_size=7),
        Spacer(1, 6),
        Paragraph(
            f"Filter order: {' -> '.join(manifest['filter_order'])}. Exclusion window "
            f"{manifest['exclusion_days']} days. Config hash "
            f"{manifest['config_hash'][:16]}...",
            st["small"],
        ),
        PageBreak(),
    ]

    # 6. Experiment ----------------------------------------------------------------------
    def row(name: str, r: dict) -> dict:
        return {
            "metric": name,
            "broad": f"{r['x_a']:,}/{r['n_a']:,} ({_pct(r['p_a'])})",
            "targeted": f"{r['x_b']:,}/{r['n_b']:,} ({_pct(r['p_b'])})",
            "diff (pp)": f"{100 * r['diff']:+.2f}",
            "95% CI (pp)": f"[{100 * r['ci_low']:+.2f}, {100 * r['ci_high']:+.2f}]",
            "z": f"{r['z']:.2f}",
            "p": f"{r['p_value']:.2g}",
        }

    plan = ro["planning"]
    E += [
        Paragraph("Experiment readout: broad vs targeted", st["h2"]),
        _img(fig / "experiment.png"),
        Spacer(1, 6),
        _table(pd.DataFrame([row("Acquisition", acq), row("Retention (30d repeat)", ret)])),
        Spacer(1, 6),
        Paragraph(
            f"Planning: to detect a {int(100 * plan['relative_lift_to_detect'])}% "
            f"relative lift on a {_pct(plan['baseline_acquisition_rate'])} baseline "
            f"(alpha {plan['alpha']}, power {plan['power']}) needs "
            f"{plan['required_n_per_arm'] or 'n/a'} users per arm.",
            st["body"],
        ),
        Spacer(1, 6),
        Paragraph(f"<b>Caveat.</b> {ro['disclaimer']}", st["body"]),
    ]

    doc.build(E, onFirstPage=_footer, onLaterPages=_footer)
    log.info("report written to %s", out)
    return out
